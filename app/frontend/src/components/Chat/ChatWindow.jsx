import { useEffect, useState } from "react";
import MessageList from "./MessageList";
import ChatInput from "./ChatInput";
import RoadmapTimeline from "../Roadmap/RoadmapTimeline";
import {
  decideRoadmapProposal,
  getCareerRoadmap,
  getRoadmapProposals,
  getToken,
  sendCareerMessage,
  updateCareerRoadmap
} from "../../lib/api";
import "./Chat.css";

const LOGIN_MESSAGE = "Please log in to chat with your career guide.";

function proposalMessage(id, proposal) {
  return {
    id: `proposal-${id}`,
    role: "proposal",
    proposalId: id,
    proposal,
    status: "pending",
    busy: false,
    error: null
  };
}

export default function ChatWindow() {
  const [messages, setMessages] = useState([
    {
      id: "welcome",
      role: "assistant",
      content:
        "Hi! I'm your career guide. What would you like to explore?"
    }
  ]);

  const [isLoading, setIsLoading] = useState(false);

  // The student's approved (official) roadmap, as stored by the backend.
  const [roadmap, setRoadmap] = useState(null);
  const [isSavingRoadmap, setIsSavingRoadmap] = useState(false);
  const [roadmapError, setRoadmapError] = useState(null);

  function addMessage(role, content) {
    setMessages(prev => [
      ...prev,
      { id: crypto.randomUUID(), role, content }
    ]);
  }

  // Adds proposals, skipping any already shown (avoids duplicates when the
  // initial load and a new chat reply overlap).
  function addProposals(items) {
    setMessages(prev => {
      const shown = new Set(prev.map(m => m.id));
      const fresh = items.filter(m => !shown.has(m.id));
      return fresh.length ? [...prev, ...fresh] : prev;
    });
  }

  function patchMessage(id, fields) {
    setMessages(prev =>
      prev.map(m => (m.id === id ? { ...m, ...fields } : m))
    );
  }

  async function loadRoadmap() {
    try {
      setRoadmap(await getCareerRoadmap());
    } catch (error) {
      console.error(error);
    }
  }

  // On open: load the official roadmap and any proposals still awaiting review.
  useEffect(() => {
    if (!getToken()) return;

    getCareerRoadmap()
      .then(setRoadmap)
      .catch(error => console.error(error));

    getRoadmapProposals()
      .then(items => {
        // API returns newest first; show oldest first like a conversation.
        addProposals(
          [...items].reverse().map(p => proposalMessage(p.id, p))
        );
      })
      .catch(error => console.error(error));
  }, []);

  async function handleSend(content) {
    if (!content.trim() || isLoading) return;

    addMessage("user", content);

    if (!getToken()) {
      addMessage("error", LOGIN_MESSAGE);
      return;
    }

    setIsLoading(true);

    try {
      const response = await sendCareerMessage(content);

      addMessage(
        "assistant",
        response?.reply || "I couldn't generate a response."
      );

      // A roadmap generated by OpenAI and validated + stored by the backend
      // as a pending proposal.
      if (response?.proposal_id && response.proposal) {
        addProposals([
          proposalMessage(response.proposal_id, response.proposal)
        ]);
      }
    } catch (error) {
      console.error(error);
      addMessage(
        "error",
        error.status === 401 ? LOGIN_MESSAGE : error.message
      );
    } finally {
      setIsLoading(false);
    }
  }

  async function handleDecide(message, decision) {
    patchMessage(message.id, { busy: true, error: null });

    try {
      const result = await decideRoadmapProposal(message.proposalId, decision);
      patchMessage(message.id, { busy: false, status: result.status });

      if (result.status === "approved") {
        await loadRoadmap();
      }
    } catch (error) {
      console.error(error);
      patchMessage(message.id, {
        busy: false,
        error: error.status === 401 ? LOGIN_MESSAGE : error.message
      });
    }
  }

  // Ticking a milestone is an owner edit to the approved roadmap (PUT /career/roadmap).
  async function handleToggleMilestone(goalId, milestoneId) {
    if (!roadmap || isSavingRoadmap) return;

    const previous = roadmap;
    const next = {
      ...roadmap,
      goals: roadmap.goals.map(goal =>
        goal.id !== goalId
          ? goal
          : {
              ...goal,
              milestones: goal.milestones.map(m =>
                m.id === milestoneId ? { ...m, completed: !m.completed } : m
              )
            }
      )
    };

    setRoadmap(next);
    setIsSavingRoadmap(true);
    setRoadmapError(null);

    try {
      setRoadmap(await updateCareerRoadmap(next));
    } catch (error) {
      console.error(error);
      setRoadmap(previous);
      setRoadmapError(error.message);
    } finally {
      setIsSavingRoadmap(false);
    }
  }

  return (
    <div className="chat-window">
      {roadmap && (
        <details className="chat-official-roadmap">
          <summary>Your approved roadmap</summary>
          <RoadmapTimeline
            roadmap={roadmap}
            onToggleMilestone={handleToggleMilestone}
            disabled={isSavingRoadmap}
          />
          {roadmapError && (
            <p className="chat-proposal-error">{roadmapError}</p>
          )}
        </details>
      )}

      <MessageList
        messages={messages}
        isLoading={isLoading}
        onDecide={handleDecide}
      />

      <ChatInput
        onSend={handleSend}
        disabled={isLoading}
      />
    </div>
  );
}
